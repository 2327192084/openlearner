/**
 * PPT 生成的内容单位。
 *
 * ## 为什么现在改成「原文段落」而不是「知识点」
 *
 * 早先 PPT 是从**已经整理好的知识点**出发的：
 *
 *     资料 → (AI) → 知识点 → (AI) → PPT
 *
 * 也就是 PPT 内容其实是知识点的二次加工。但那不是用户要的：
 * 课件应当根据**资料原文**生成，并按用户选的页码范围取材 ——
 * 与知识点那一栏是同一个取材方式。
 *
 * 现在：
 *
 *     资料（可选页码范围）→ (AI) → PPT
 *
 * ## 角标反而更准了
 *
 * 角标链路从
 *     要点 → 引用 → knowledgePointId → 知识点.anchors → 页码
 * 缩短成
 *     要点 → 引用 → segmentId → 段落.page
 *
 * 少一跳，也不再依赖「知识点必须定位成功」。原先是知识点定位失败就
 * 没有角标；现在只要段落有页码（几乎所有情况都有），角标就一定成立。
 */

/** 送给模型的一段原始资料 */
export interface SourceChunk {
  /** 段 id。模型要指回它，我们据此建角标 */
  segmentId: string;
  /** 页码，从 1 开始。**角标的页码直接来自这里** */
  page: number;
  /** 所属章节，没有则 null */
  chapter: string | null;
  /** 规范化后的正文 */
  text: string;
}

/**
 * 模型返回的一条要点的出处。
 *
 * 模型只需要说「这一条来自哪一段」，页码由我们从段落继承 ——
 * 它看不到分页，让它给页码只会得到编造的结果。
 */
export interface ChunkRef {
  segmentId: string;
}
